def build_lessons(profile: ProfileSource) -> list[dict]:
    """Return fresh draft lessons; profile links use stable IDs, never slot numbers."""
    required_slots = {
        slot_id for material in _LESSONS.values() for slot_id in material["related_slot_ids"]
    }
    missing_slots = required_slots - {slot.id for slot in profile.slots}
    if missing_slots:
        raise ValueError("Foundations require related profile slots: " + ", ".join(
            sorted(missing_slots),
        ))
    return [
        {
            "id": f"base-{topic}",
            "slot": 0,
            "slot_id": None,
            "kind": "foundation",
            "skill_ids": [f"foundation-{topic}"],
            "family_ids": [],
            "practice_task_ids": [],
            "review_status": "demo",
            "author_id": "ai-project",
            "reviewed_by": None,
            **deepcopy(material),
        }
        for topic, material in _LESSONS.items()
    ]
